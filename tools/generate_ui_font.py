"""生成面板用思源黑体子集；需要 Node.js/npm 和官方 SourceHanSansCN-Regular.otf。"""

from pathlib import Path
import subprocess
import sys


def main():
    root = Path(__file__).resolve().parents[1]
    font = root / "build/ui-font/SourceHanSansCN-Regular.otf"
    if not font.is_file():
        sys.exit("请先下载思源黑体到 build/ui-font/SourceHanSansCN-Regular.otf")

    # GB2312 一级汉字覆盖常用识别文本；加上界面中用到的少量二级字和标点。
    symbols = set()
    for first in range(0xB0, 0xD8):
        for second in range(0xA1, 0xFF):
            try:
                symbols.add(bytes([first, second]).decode("gb2312"))
            except UnicodeDecodeError:
                pass

    dashboard = root / "components/ui/src/dashboard.cpp"
    symbols.update(c for c in dashboard.read_text(encoding="utf-8") if "\u3400" <= c <= "\u9fff")
    symbols.update("嗨乐鑫「」，。！？：、…（）")
    output = root / "components/ui/fonts/ui_font_chinese_16.c"
    output.parent.mkdir(parents=True, exist_ok=True)

    subprocess.run(
        [
            "npm.cmd", "exec", "--yes", "--package=lv_font_conv@1.5.3", "--", "lv_font_conv",
            "--font", str(font),
            "--size", "16",
            "--bpp", "2",
            "--format", "lvgl",
            "--range", "0x20-0x7E",
            "--symbols", "".join(sorted(symbols)),
            "--no-compress",
            "--no-kerning",
            "--lv-font-name", "ui_font_chinese_16",
            "--output", str(output),
        ],
        check=True,
        cwd=root,
    )

    # 转换器头部带本机路径和整份字符列表，改成可读的生成说明。
    source = output.read_text(encoding="utf-8")
    source = source[source.index("#ifndef UI_FONT_CHINESE_16"):]
    source = source.replace(
        "    .dsc = &font_dsc,",
        "#if LV_VERSION_CHECK(9, 3, 0)\n"
        "    .static_bitmap = 1,\n"
        "#endif\n"
        "    .dsc = &font_dsc,",
    )
    header = (
        "/* Generated by tools/generate_ui_font.py with lv_font_conv 1.5.3.\n"
        " * 16px, 2bpp, GB2312 level-1 + UI glyphs; bitmap stored in flash.\n"
        " * Source Han Sans CN: SIL Open Font License, see LICENSE.txt.\n"
        " */\n"
    )
    output.write_text(
        (header + '#include <lvgl.h>\n\n' + source).rstrip() + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {len(symbols)} CJK/punctuation glyphs plus ASCII.")


if __name__ == "__main__":
    main()
